# Longest keys first so multi-word shortcodes match correctly.
_KEYS = sorted(EMOJI_MAP.keys(), key=len, reverse=True)
_PATTERN = re.compile("|".join(re.escape(k) for k in _KEYS))


def render_emoji(text):
    """Replace emoji shortcodes like :smile: with Unicode characters."""
    if not text:
        return text
    return _PATTERN.sub(lambda m: EMOJI_MAP[m.group(0)], text)
